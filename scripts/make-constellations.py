#!/usr/bin/env python3
"""Writes src/bg/constellations.ts from the HYG star catalogue.

Usage: python3 scripts/make-constellations.py path/to/hygdata_v41.csv
The catalogue is at https://github.com/astronexus/HYG-Database (hyg/CURRENT/hygdata_v41.csv).
"""
import csv
import json
import sys

GREEK = {'Alp': 'Alpha', 'Bet': 'Beta', 'Gam': 'Gamma', 'Del': 'Delta', 'Eps': 'Epsilon', 'Zet': 'Zeta', 'Eta': 'Eta',
         'The': 'Theta', 'Iot': 'Iota', 'Kap': 'Kappa', 'Lam': 'Lambda', 'Mu': 'Mu', 'Pi': 'Pi', 'Sig': 'Sigma',
         'Tau': 'Tau', 'Ups': 'Upsilon'}

# id, name, meaning, genitive, stars (Bayer letters), lines (pairs of Bayer letters)
FIGURES = [
    ('Ori', 'Orion', 'the Hunter', 'Orionis', ['Alp', 'Bet', 'Gam', 'Kap', 'Zet', 'Eps', 'Del', 'Lam'],
     ['Alp-Gam', 'Alp-Zet', 'Gam-Del', 'Zet-Eps', 'Eps-Del', 'Zet-Kap', 'Del-Bet', 'Kap-Bet', 'Lam-Alp', 'Lam-Gam']),
    ('UMa', 'Ursa Major', 'the Great Bear, with the Big Dipper', 'Ursae Majoris', ['Alp', 'Bet', 'Gam', 'Del', 'Eps', 'Zet', 'Eta'],
     ['Alp-Bet', 'Bet-Gam', 'Gam-Del', 'Del-Alp', 'Del-Eps', 'Eps-Zet', 'Zet-Eta']),
    ('Cas', 'Cassiopeia', 'the Queen', 'Cassiopeiae', ['Bet', 'Alp', 'Gam', 'Del', 'Eps'],
     ['Bet-Alp', 'Alp-Gam', 'Gam-Del', 'Del-Eps']),
    ('Cru', 'Crux', 'the Southern Cross', 'Crucis', ['Alp', 'Bet', 'Gam', 'Del'], ['Alp-Gam', 'Bet-Del']),
    ('Cyg', 'Cygnus', 'the Swan', 'Cygni', ['Alp', 'Gam', 'Eps', 'Del', 'Bet'], ['Alp-Gam', 'Gam-Bet', 'Eps-Gam', 'Gam-Del']),
    ('Leo', 'Leo', 'the Lion', 'Leonis', ['Alp', 'Bet', 'Gam', 'Del', 'The', 'Zet', 'Mu', 'Eps', 'Eta'],
     ['Alp-Eta', 'Eta-Gam', 'Gam-Zet', 'Zet-Mu', 'Mu-Eps', 'Gam-Del', 'Del-Bet', 'Bet-The', 'The-Alp', 'Del-The']),
    ('Sco', 'Scorpius', 'the Scorpion', 'Scorpii',
     ['Bet', 'Del', 'Pi', 'Sig', 'Alp', 'Tau', 'Eps', 'Mu', 'Zet', 'Eta', 'The', 'Iot', 'Kap', 'Lam', 'Ups'],
     ['Bet-Del', 'Del-Pi', 'Del-Sig', 'Sig-Alp', 'Alp-Tau', 'Tau-Eps', 'Eps-Mu', 'Mu-Zet', 'Zet-Eta', 'Eta-The', 'The-Iot',
      'Iot-Kap', 'Kap-Lam', 'Lam-Ups']),
    ('Lyr', 'Lyra', 'the Lyre', 'Lyrae', ['Alp', 'Bet', 'Gam', 'Del', 'Zet'], ['Alp-Zet', 'Zet-Del', 'Del-Gam', 'Gam-Bet', 'Bet-Zet']),
    ('Gem', 'Gemini', 'the Twins', 'Geminorum', ['Alp', 'Bet', 'Gam', 'Eps', 'Mu', 'Del', 'Eta'],
     ['Alp-Bet', 'Alp-Eps', 'Eps-Mu', 'Mu-Eta', 'Bet-Del', 'Del-Gam']),
    ('Tau', 'Taurus', 'the Bull', 'Tauri', ['Alp', 'Bet', 'Zet', 'Eps', 'Gam', 'Lam'],
     ['Bet-Eps', 'Eps-Gam', 'Gam-Alp', 'Alp-Zet', 'Gam-Lam']),
    ('CMa', 'Canis Major', 'the Great Dog', 'Canis Majoris', ['Alp', 'Bet', 'Eps', 'Del', 'Eta'],
     ['Bet-Alp', 'Alp-Del', 'Del-Eta', 'Del-Eps']),
]


def main():
    rows = list(csv.DictReader(open(sys.argv[1], newline='')))
    out = []
    for con, name, meaning, genitive, letters, lines in FIGURES:
        stars = []
        for letter in letters:
            # "Bet-1" and "Del-2" are components of one Bayer letter: take the brightest.
            found = [r for r in rows if r['con'] == con and r['bayer'] and r['bayer'].split('-')[0].rstrip('0123456789 ') == letter]
            if not found:
                sys.exit(f'{letter} {con} not found')
            r = min(found, key=lambda x: float(x['mag']))
            stars.append({
                'name': r['proper'] or f'{GREEK[letter]} {genitive}',
                'ra': round(float(r['ra']), 4),
                'dec': round(float(r['dec']), 3),
                'mag': round(float(r['mag']), 2),
                'ci': round(float(r['ci']), 2) if r['ci'] else 0.6,
                'ly': round(float(r['dist']) * 3.26156),
            })
        pairs = [[letters.index(a), letters.index(b)] for a, b in (line.split('-') for line in lines)]
        out.append({'id': con, 'name': name, 'meaning': meaning, 'stars': stars, 'lines': pairs})

    body = json.dumps(out, indent=2, ensure_ascii=False)
    with open('src/bg/constellations.ts', 'w') as f:
        f.write('''/**
 * Constellation figures for the space background.
 * Generated by scripts/make-constellations.py from the HYG star catalogue v4.1
 * (https://github.com/astronexus/HYG-Database). Do not edit by hand.
 * ra is in hours, dec in degrees, ci is the B-V colour index, ly is the distance in light-years.
 */
export interface FigureStar {
  name: string;
  ra: number;
  dec: number;
  mag: number;
  ci: number;
  ly: number;
}
export interface Figure {
  id: string;
  name: string;
  meaning: string;
  stars: FigureStar[];
  /** Pairs of indexes into `stars`. */
  lines: [number, number][];
}

export const FIGURES = ''' + body + ''' as Figure[];
''')
    for fig in out:
        print(fig['name'], [s['name'] for s in fig['stars']])


main()
